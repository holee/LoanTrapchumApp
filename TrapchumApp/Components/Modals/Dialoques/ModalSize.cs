namespace TrapchumApp.Components.Modals.Dialoques;

/// <summary>Predefined sizes for a modal dialogue.</summary>
public enum ModalSize
{
    /// <summary>400 px wide – ideal for simple confirmations or short forms.</summary>
    Small,

    /// <summary>640 px wide – default; suits most forms and data dialogs.</summary>
    Medium,

    /// <summary>960 px wide – for complex forms or data-rich dialogs.</summary>
    Large,

    /// <summary>100 vw × 100 vh – occupies the full viewport.</summary>
    Fullscreen
}

